import AppKit

enum ClipboardPreference {
    static let autoIncludeKey = "quickChatAutoIncludeClipboard"

    static func autoInclude(defaults: UserDefaults = .standard) -> Bool {
        defaults.object(forKey: autoIncludeKey) as? Bool ?? true
    }

    static func reset(defaults: UserDefaults = .standard) {
        defaults.removeObject(forKey: autoIncludeKey)
    }
}

/// Timestamps `NSPasteboard` changes while automatic capture is on (DEC-057).
/// A change older than `recency` is not a Quick Chat row.
final class PasteboardMonitor {
    static let recency: TimeInterval = 60

    // NSPasteboard.org's shared markers and their established predecessors.
    // Presence is meaningful even when the marker has an empty payload.
    static let excludedAutomaticTypes: Set<NSPasteboard.PasteboardType> = Set([
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "org.nspasteboard.RestoredType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type"
    ].map { NSPasteboard.PasteboardType($0) })

    static func permitsAutomaticCapture(_ pasteboard: NSPasteboard) -> Bool {
        var types = Set(pasteboard.types ?? [])
        for item in pasteboard.pasteboardItems ?? [] { types.formUnion(item.types) }
        return types.isDisjoint(with: excludedAutomaticTypes)
    }

    var now: () -> Date = Date.init
    private var lastChangeCount: Int
    private var lastChangeAt: Date?
    private var timer: Timer?

    init(pasteboard: NSPasteboard = .general) {
        lastChangeCount = pasteboard.changeCount
    }

    var isPolling: Bool { timer != nil }

    /// Follow the clipboard preference. Off means no polling at all, and
    /// turning it back on starts from the current pasteboard, so nothing
    /// copied while it was off counts as recent.
    func sync(enabled: Bool, pasteboard: NSPasteboard = .general) {
        if enabled {
            start(pasteboard: pasteboard)
        } else {
            stop()
        }
    }

    func start(pasteboard: NSPasteboard = .general) {
        guard timer == nil else { return }
        lastChangeCount = pasteboard.changeCount
        let timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            self?.poll(pasteboard)
        }
        timer.tolerance = 0.2
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        lastChangeAt = nil
    }

    func poll(_ pasteboard: NSPasteboard = .general) {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        lastChangeAt = now()
    }

    /// Test hook: pretend the pasteboard changed at `date`.
    func markChanged(at date: Date? = nil) {
        lastChangeAt = date ?? now()
    }

    func isRecent(at date: Date? = nil) -> Bool {
        guard let lastChangeAt else { return false }
        return (date ?? now()).timeIntervalSince(lastChangeAt) <= Self.recency
    }

    struct Snapshot: Equatable {
        var text: String?
        var attachments: [QuickChatAttachment]
        var copiedAt: Date?
        var fileURLs: [URL] = []
        var imageData: Data? = nil
    }

    /// Files win, then an image, then text. Stale pasteboard is empty.
    func snapshotIfRecent(
        pasteboard: NSPasteboard = .general,
        defaults: UserDefaults = .standard
    ) -> Snapshot? {
        let changeCount = pasteboard.changeCount
        guard ClipboardPreference.autoInclude(defaults: defaults),
              isRecent(), Self.permitsAutomaticCapture(pasteboard) else { return nil }
        let snapshot = capture(pasteboard)
        guard pasteboard.changeCount == changeCount,
              Self.permitsAutomaticCapture(pasteboard) else { return nil }
        return snapshot
    }

    private func capture(_ pasteboard: NSPasteboard) -> Snapshot {
        let copiedAt = lastChangeAt
        let files = FileIntake.fileURLs(from: pasteboard, validate: false)
        if !files.isEmpty {
            return Snapshot(text: nil, attachments: [], copiedAt: copiedAt, fileURLs: files)
        }
        if let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff) {
            return Snapshot(text: nil, attachments: [], copiedAt: copiedAt, imageData: data)
        }
        if let text = pasteboard.string(forType: .string)?
            .trimmingCharacters(in: .whitespacesAndNewlines),
           !text.isEmpty {
            return Snapshot(text: text, attachments: [], copiedAt: copiedAt)
        }
        return Snapshot(text: nil, attachments: [], copiedAt: copiedAt)
    }
}
